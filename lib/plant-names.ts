// Get a random name suggestion for a plant type
export function getRandomPlantName(plantType: string): string {
  // Normalize the plant type (lowercase, remove common words)
  const normalized = plantType.toLowerCase()
    .replace(/plant|tree|vine|bush/gi, '')
    .trim()
  
  // Try to find exact match
  if (plantNames[normalized]) {
    const names = plantNames[normalized]
    return names[Math.floor(Math.random() * names.length)]
  }
  
  // Try to find partial match
  for (const [key, names] of Object.entries(plantNames)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return names[Math.floor(Math.random() * names.length)]
    }
  }
  
  // Return a generic funny name if no match
  const defaultNames = plantNames.default
  return defaultNames[Math.floor(Math.random() * defaultNames.length)]
}

// Get all suggestions for a plant type (for dropdown)
export function getAllPlantNames(plantType: string): string[] {
  const normalized = plantType.toLowerCase()
    .replace(/plant|tree|vine|bush/gi, '')
    .trim()
  
  if (plantNames[normalized]) {
    return plantNames[normalized]
  }
  
  // Try partial match
  for (const [key, names] of Object.entries(plantNames)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return names
    }
  }
  
  return plantNames.default
}